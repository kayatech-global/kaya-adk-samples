"""Built-in deploy targets: a container image, Kubernetes manifests, ADK's own deploy commands, and placeholders.

``docker`` and ``kubernetes`` run the governed run host by default (authentication, authorization, approvals, A2A), which
fails closed in production until real identity providers are configured. ``entrypoint=adk`` serves ADK's own API
(``server.py:app``) instead, which has no authentication and must sit behind an authenticating gateway.
``cloud_run``, ``gke`` and ``agent_engine`` hand the agent folder to ``adk deploy``, which serves it with ``adk api_server``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Literal

import yaml

from ..factories.base import ProviderSettings
from ..factories.registry import register
from .base import DeployPlan, DeployProject, DeployTarget, PlaceholderTarget

_DOCKERIGNORE = """\
**/.venv
**/__pycache__
**/.pytest_cache
**/.mypy_cache
**/.ruff_cache
**/.adk
**/.env
**/.env.*
build
tests
docs
deployment
reports
sonar-project.properties
"""


def dockerfile(project: DeployProject, *, base_image: str, port: int, entrypoint: str, profile: str) -> str:
    """A Dockerfile for the package: pinned requirements, the source folder, a non-root user and a health check."""
    pkg = project.package
    if entrypoint == "run_host":
        cmd = ["uvicorn", "--factory", f"{pkg}.server:create_run_host", "--host", "0.0.0.0", "--port", str(port)]  # noqa: S104
    else:  # ADK's own API server (<pkg>/server.py), which also continues the caller's W3C trace
        cmd = ["uvicorn", f"{pkg}.server:app", "--host", "0.0.0.0", "--port", str(port)]  # noqa: S104
    health = _health(entrypoint)[1]
    probe = f"import urllib.request; urllib.request.urlopen('http://127.0.0.1:{port}{health}', timeout=3)"
    return f"""\
# Generated by `python {pkg}/deployment/deploy.py docker`; regenerate it instead of editing it.
FROM {base_image}
ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PYTHONPATH=/app FLOW_PROFILE={profile}
WORKDIR /app
RUN useradd --create-home --uid 10001 app
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY . ./{pkg}
USER app
EXPOSE {port}
HEALTHCHECK --interval=30s --timeout=5s --start-period=20s CMD {json.dumps(["python", "-c", probe])}
CMD {json.dumps(cmd)}
"""


_ADK_WARNING = (
    "entrypoint=adk serves ADK's API with no authentication, authorization or approvals (any caller can run the agent and "
    "read any session): put it behind an authenticating gateway, or use the default run host"
)


def _health(entrypoint: str) -> tuple[str, str]:
    """``(readiness, liveness)`` paths of the server an image runs."""
    return ("/readyz", "/healthz") if entrypoint == "run_host" else ("/health", "/health")


class _ImageSettings(ProviderSettings):
    image: str = ""  # default: <service name>:<export version>
    base_image: str = "python:3.13-slim"
    port: int = 8080
    entrypoint: Literal["run_host", "adk"] = "run_host"  # the governed run host, or ADK's unauthenticated API (server.py:app)


@register
class DockerTarget(DeployTarget):
    """A container image of the package, built with ``docker build`` and optionally started locally."""

    name = "docker"
    summary = "container image of the agent's server (docker build; --set run=true also starts it)"

    class Settings(_ImageSettings):
        profile: Literal["development", "production"] = "development"
        run: bool = False
        env_file: str = ""  # passed to `docker run --env-file`, for example <pkg>/.env

    def plan(self, project: DeployProject, out: Path) -> DeployPlan:
        """Dockerfile and .dockerignore in the output folder; ``docker build`` (and ``docker run``) from the project folder."""
        s = self.settings
        image = s.image or f"{project.service_name}:{project.export_version}"
        p = DeployPlan(self.name)
        p.files["Dockerfile"] = dockerfile(project, base_image=s.base_image, port=s.port, entrypoint=s.entrypoint, profile=s.profile)
        p.files["Dockerfile.dockerignore"] = _DOCKERIGNORE
        p.commands.append(["docker", "build", "-f", str(out / "Dockerfile"), "-t", image, str(project.root)])
        if s.run:
            env = ["--env-file", s.env_file] if s.env_file else []
            p.commands.append(["docker", "run", "-d", "--name", project.service_name, "-p", f"{s.port}:{s.port}", *env, image])
        p.notes.append("BuildKit reads Dockerfile.dockerignore next to the Dockerfile, so local env files and caches never enter the image")
        if s.entrypoint == "adk":
            p.notes.append(_ADK_WARNING)
        if project.secret_env:
            p.notes.append(f"pass these at run time, never at build time: {', '.join(project.secret_env)}")
        return p


@register
class KubernetesTarget(DeployTarget):
    """Deployment and Service manifests for any Kubernetes cluster. Writes files only; apply them with your own tooling."""

    name = "kubernetes"
    summary = "Deployment + Service manifests for any cluster (written, never applied)"

    class Settings(_ImageSettings):
        namespace: str = "default"
        replicas: int = 2
        secret_name: str = ""  # a Secret holding the model keys and logical secrets, mounted as environment variables
        service_type: Literal["ClusterIP", "LoadBalancer", "NodePort"] = "ClusterIP"
        profile: Literal["development", "production"] = "production"

    def plan(self, project: DeployProject, out: Path) -> DeployPlan:
        """``kubernetes.yaml`` with a Deployment (health probes) and a Service; no command is run."""
        s = self.settings
        name = project.service_name
        image = s.image or f"{name}:{project.export_version}"
        secret = s.secret_name or f"{name}-secrets"
        ready, live = _health(s.entrypoint)
        labels = {"app.kubernetes.io/name": name, "app.kubernetes.io/version": project.export_version}
        deployment = {
            "apiVersion": "apps/v1",
            "kind": "Deployment",
            "metadata": {"name": name, "namespace": s.namespace, "labels": dict(labels)},
            "spec": {
                "replicas": s.replicas,
                "selector": {"matchLabels": {"app.kubernetes.io/name": name}},
                "template": {
                    "metadata": {"labels": dict(labels)},
                    "spec": {
                        "securityContext": {"runAsNonRoot": True, "runAsUser": 10001},
                        "containers": [
                            {
                                "name": name,
                                "image": image,
                                "ports": [{"containerPort": s.port, "name": "http"}],
                                "env": [
                                    {"name": "FLOW_PROFILE", "value": s.profile},
                                ],
                                "envFrom": [{"secretRef": {"name": secret, "optional": True}}],
                                "readinessProbe": {"httpGet": {"path": ready, "port": "http"}, "periodSeconds": 10},
                                "livenessProbe": {"httpGet": {"path": live, "port": "http"}, "periodSeconds": 30},
                                "securityContext": {"allowPrivilegeEscalation": False},
                            }
                        ],
                    },
                },
            },
        }
        service = {
            "apiVersion": "v1",
            "kind": "Service",
            "metadata": {"name": name, "namespace": s.namespace, "labels": dict(labels)},
            "spec": {"type": s.service_type, "selector": {"app.kubernetes.io/name": name}, "ports": [{"port": 80, "targetPort": "http"}]},
        }
        p = DeployPlan(self.name)
        p.files["kubernetes.yaml"] = yaml.safe_dump_all([deployment, service], sort_keys=False)
        p.notes.append(f"build and push the image first (target 'docker' with --set image={image}), then review and apply kubernetes.yaml")
        keys = ", ".join(project.secret_env) or "the model keys"
        p.notes.append(f"create Secret '{secret}' in namespace '{s.namespace}' with {keys}")
        if s.profile == "production" and s.entrypoint == "run_host":
            p.notes.append("FLOW_PROFILE=production: /readyz stays 503 until settings.build_providers(...) returns a real authn provider")
        if s.entrypoint == "adk":
            p.notes.append(_ADK_WARNING)
        return p


class _AdkDeploy(DeployTarget):
    """A target served by ADK's own `adk deploy <command>` (adk api_server in a generated image)."""

    command = ""

    def flags(self, project: DeployProject) -> list[str]:
        """The command-line flags of this target."""
        return []

    def plan(self, project: DeployProject, out: Path) -> DeployPlan:
        """One `adk deploy` command over the agent folder; ADK generates its own Dockerfile."""
        p = DeployPlan(self.name)
        p.commands.append(["adk", "deploy", self.command, *self.flags(project), str(project.agent_dir)])
        p.notes.append("ADK serves the agent with `adk api_server` (ADK sessions, no run-host authentication, approvals or trace)")
        if project.secret_env:
            p.notes.append(f"give the service these variables from your secret store: {', '.join(project.secret_env)}")
        if "session_service_uri" in type(self.settings).model_fields and not self.settings.session_service_uri:
            p.notes.append("no session_service_uri: ADK keeps sessions in memory, so a paused review is lost on a restart or a second instance")
        return p


class _GcpSettings(ProviderSettings):
    project: str = ""
    region: str = ""
    service_name: str = ""


class _ServedSettings(_GcpSettings):
    session_service_uri: str = ""  # a database for ADK's sessions (`--session_service_uri`); paused runs live there


def _session_flags(s: _ServedSettings) -> list[str]:
    return ["--session_service_uri", s.session_service_uri] if s.session_service_uri else []


@register
class CloudRunTarget(_AdkDeploy):
    """Google Cloud Run through `adk deploy cloud_run` (needs gcloud)."""

    name = "cloud_run"
    command = "cloud_run"
    summary = "Google Cloud Run via `adk deploy cloud_run`"

    class Settings(_ServedSettings):
        with_ui: bool = False
        a2a: bool = False

    def flags(self, project: DeployProject) -> list[str]:
        """--project, --region, --service_name and the switches that are set."""
        s = self.settings
        out = _gcp_flags(s.project, s.region) + ["--service_name", s.service_name or project.service_name]
        return out + _session_flags(s) + (["--with_ui"] if s.with_ui else []) + (["--a2a"] if s.a2a else [])


@register
class GkeTarget(_AdkDeploy):
    """Google Kubernetes Engine through `adk deploy gke` (needs gcloud and kubectl)."""

    name = "gke"
    command = "gke"
    summary = "Google Kubernetes Engine via `adk deploy gke`"

    class Settings(_ServedSettings):
        cluster_name: str = ""
        service_type: Literal["ClusterIP", "LoadBalancer"] = "ClusterIP"

    def flags(self, project: DeployProject) -> list[str]:
        """--project, --region, --cluster_name, --service_name and --service_type."""
        s = self.settings
        return _gcp_flags(s.project, s.region) + [
            "--cluster_name",
            s.cluster_name or "<cluster>",
            "--service_name",
            s.service_name or project.service_name,
            "--service_type",
            s.service_type,
            *_session_flags(s),
        ]


@register
class AgentEngineTarget(_AdkDeploy):
    """Vertex AI Agent Engine through `adk deploy agent_engine`."""

    name = "agent_engine"
    command = "agent_engine"
    summary = "Vertex AI Agent Engine via `adk deploy agent_engine`"

    class Settings(_GcpSettings):
        display_name: str = ""
        agent_engine_id: str = ""  # update this engine in place instead of creating one

    def flags(self, project: DeployProject) -> list[str]:
        """--project, --region, --display_name and, when updating, --agent_engine_id."""
        s = self.settings
        out = _gcp_flags(s.project, s.region) + ["--display_name", s.display_name or project.package]
        return out + (["--agent_engine_id", s.agent_engine_id] if s.agent_engine_id else [])


def _gcp_flags(project: str, region: str) -> list[str]:
    return (["--project", project] if project else []) + (["--region", region] if region else [])


